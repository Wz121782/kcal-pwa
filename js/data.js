  function pinnedFoods() {
    var out = [], seen = {};
    for (var i = 0; i < PINNED.length; i++) {
      var f = null;
      for (var j = 0; j < FOODS.length; j++) {
        if (FOODS[j].n === PINNED[i]) { f = FOODS[j]; break; }
      }
      if (f && !seen[f.n]) { seen[f.n] = 1; out.push(f); }
    }
    return out;
  }

  function searchFood(q, limit) {
    limit = limit || 40;
    var key = String(q || '').trim().toLowerCase();
    if (!key) {
      // 空查询：常吃清单打头，再补一些库里的条目
      var pin = pinnedFoods();
      if (pin.length >= limit) return pin.slice(0, limit);
      var got = {}, rest = [];
      pin.forEach(function (f) { got[f.n] = 1; });
      for (var n = 0; n < FOODS.length && rest.length < limit - pin.length; n++) {
        if (!got[FOODS[n].n]) { got[FOODS[n].n] = 1; rest.push(FOODS[n]); }
      }
      return pin.concat(rest);
    }
    var hit = [], inc = [];
    for (var i = 0; i < FOODS.length; i++) {
      var f = FOODS[i];
      var n = f.n.toLowerCase();
      if (n === key) hit.push(f);
      else if (n.indexOf(key) === 0) hit.push(f);
      else if (n.indexOf(key) > -1) inc.push(f);
    }
    return hit.concat(inc).slice(0, limit);
  }

  function findFood(name) {
    for (var i = 0; i < FOODS.length; i++) {
      if (FOODS[i].n === name) return FOODS[i];
    }
    return null;
  }

  /** 为一个食物条目生成手绘注解短句：烹饪方式 + 食材分类 */
  function autoNote(food, userNote) {
    if (userNote && String(userNote).trim()) return String(userNote).trim();
    var pool = COOK[food.c] || COOK.x;
    var cook = pool[Math.floor(Math.random() * pool.length)];
    var catLabel = (CAT[food.c] || CAT.x).label;
    return cook + ' · ' + catLabel;
  }

